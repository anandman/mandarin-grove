#!/usr/bin/env node
// Offline reconstruction from licensed lexical rows and explicit compatibility facts.
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const ROOT=path.resolve(__dirname,'..');
const GRADES=['K','1','2','3','4','5'];
const SUPPLEMENTS=[...'雨牙鱼牛羊车爱朋友'];
function parseCedict(text){
 return String(text).split(/\r?\n/).flatMap(line=>{
  const match=line.match(/^(\S+) (\S+) \[([^\]]+)\] \/(.+)\/$/);
  return match?[{traditional:match[1],simplified:match[2],pinyin:match[3],definitions:match[4].split('/'),line}]:[];
 });
}
function readingKey(value){
 const text=String(value).toLowerCase().replace(/u:/g,'ü').replace(/v/g,'ü').normalize('NFD');
 const marks=['\u0304','\u0301','\u030c','\u0300'];let base='',tone=5;
 for(const ch of text){
  if(/[1-5]/.test(ch))tone=Number(ch);
  else if(ch==='\u0308'&&base.endsWith('u'))base=base.slice(0,-1)+'v';
  else if(marks.includes(ch))tone=marks.indexOf(ch)+1;
  else if(/[a-z]/.test(ch))base+=ch;
 }
 return base+tone;
}
function buildCurriculum({units,compatibility,dictionary,source,supplements=SUPPLEMENTS}){
 const taught=new Map(compatibility.map(item=>[item.character,item.pinyin]));
 const grades={};for(const grade of GRADES)if(units[grade])grades[grade]=units[grade].map(([,text])=>text).join('')+(grade==='K'?supplements.join(''):'');
 const ids=[...new Set(Object.values(grades).flatMap(text=>[...text]))];
 const defaultCharacters=(units['2']||[]).slice(0,6).flatMap(([,text])=>[...text]),defaults=new Set(defaultCharacters);
 const review={directHeadwordReadings:0,pronunciationNoteReadings:0,unsupportedReadings:[],semantic:'dictionary-derived; not fluently or teacher reviewed; no audio verification'};
 const cards=ids.map(character=>{
  if(!taught.has(character))throw Error('Missing taught-reading compatibility fact: '+character);
  const candidates=dictionary.filter(row=>row.simplified===character).sort((a,b)=>Number(a.pinyin!==a.pinyin.toLowerCase())-Number(b.pinyin!==b.pinyin.toLowerCase()));
  const p=taught.get(character),readings=p.split(/\s*\/\s*/).map(pinyin=>{
   const key=readingKey(pinyin);let rows=candidates.filter(row=>readingKey(row.pinyin)===key),kind='headword';
   if(rows.some(row=>row.pinyin===row.pinyin.toLowerCase()))rows=rows.filter(row=>row.pinyin===row.pinyin.toLowerCase());
   if(!rows.length){rows=candidates.filter(row=>row.definitions.some(definition=>/\bpr\.|\bpronunciation|\bpronounced/i.test(definition)&&[...definition.matchAll(/\[([^\]]+)\]/g)].some(match=>readingKey(match[1])===key)));kind=rows.length?'pronunciation-note':'unsupported';}
   const substantive=rows.filter(row=>row.definitions.some(definition=>!/^(?:old |archaic |ancient )?(?:variant|same as|see )/i.test(definition)));
   if(substantive.length)rows=substantive;
   if(kind==='headword')review.directHeadwordReadings++;
   else if(kind==='pronunciation-note')review.pronunciationNoteReadings++;
   else review.unsupportedReadings.push({character,pinyin});
   const definitions=rows.flatMap(row=>row.definitions.filter(definition=>!definition.startsWith('CL:')&&!/\bpr\.|\bpronunciation|\bpronounced/i.test(definition)).slice(0,2));
   const meaning=[...new Set(definitions)].join('; ');
   return {pinyin,key,meaning,source:source.id,evidence:{kind,line:rows[0]?.line||null,lines:rows.map(row=>row.line)},review:kind==='pronunciation-note'?'context-review-pending':'dictionary-derived-unreviewed'};
  });
  return {id:character,c:character,p,m:[...new Set(readings.map(reading=>reading.meaning).filter(Boolean))].join(' / ')||'Definition pending source review',w:'',wp:'',o:defaults.has(character)?1:0,g:GRADES.filter(grade=>grades[grade]?.includes(character)).join(''),readings,
   source:{lexical:source.id,curriculum:(Object.values(units).some(list=>list.some(([,text])=>text.includes(character)))?'better-immersion-k5-fixture':'grove-kindergarten-supplement'),review:'dictionary-derived-unreviewed'}};
 });
 return {schemaVersion:1,id:'grove-curriculum',version:'1.0.0',license:'mixed-see-sources',
  sources:{lexical:source,curriculum:source.curriculum||{id:'provided-curriculum-fixture',redistribution:'publication-permission-unresolved'},compatibility:{id:'grove-legacy-taught-reading-compatibility',path:'content/reading-compatibility.json',normalizedSha256:crypto.createHash('sha256').update(JSON.stringify(compatibility)).digest('hex'),scope:'Taught c/p facts retained for continuity; not a source of fresh meanings or examples.'},supplement:{id:'grove-kindergarten-supplement',characters:supplements.join(''),scope:'Explicit supplemental membership compatibility; 羊鱼 are outside all official fixture units.'}},
  units,grades,defaultCharacters,cards,review};
}
function browserSource(pack){return '// Generated by scripts/build-curriculum.cjs from licensed data; see content/curriculum.json sources.\n(function(root){const data='+JSON.stringify(pack)+';if(typeof module===\'object\'&&module.exports)module.exports=data;else root.GroveCurriculum=data;})(typeof globalThis===\'object\'?globalThis:this);\n';}
function run(){
 const check=process.argv.slice(2).includes('--check');
 const read=file=>JSON.parse(fs.readFileSync(path.join(ROOT,file),'utf8'));
 const source=read('vendor/cc-cedict/CHARACTERS-SOURCE.json'),bytes=fs.readFileSync(path.join(ROOT,source.subset.path));
 if(crypto.createHash('sha256').update(bytes).digest('hex')!==source.subset.sha256)throw Error('Pinned character-source subset hash mismatch');
 const fixtureBytes=fs.readFileSync(path.join(ROOT,source.curriculum.path));
 if(crypto.createHash('sha256').update(fixtureBytes).digest('hex')!==source.curriculum.sha256)throw Error('Pinned curriculum fixture hash mismatch');
 const data=buildCurriculum({units:JSON.parse(fixtureBytes),compatibility:read('content/reading-compatibility.json').readings,dictionary:parseCedict(bytes.toString('utf8')),source});
 for(const [file,text] of [['content/curriculum.json',JSON.stringify(data,null,2)+'\n'],['content/curriculum.js',browserSource(data)]]){
  const target=path.join(ROOT,file);
  if(check){if(fs.readFileSync(target,'utf8')!==text)throw Error('Generated content is stale: '+file);}
  else fs.writeFileSync(target,text);
 }
 process.stdout.write(JSON.stringify({characters:data.cards.length,...data.review,checkOnly:check})+'\n');
}
if(require.main===module){try{run();}catch(error){process.stderr.write(error.message+'\n');process.exitCode=1;}}
module.exports={parseCedict,buildCurriculum};
